/** The policy itself (beyond its assumptions), for cases that have one. */
const policyChangesOf = (c) => c.policyChanges || {};

/**
 * The case's model: the scenario's glossary model with the policy and its assumptions in place,
 * each assumption's note in its variable's documentation.
 * @param {Object} c The case
 * @param {Object} glossaryModel The scenario's glossary model
 * @param {function} findVariable modelDiff.findVariable
 * @param {boolean} reverted Put the unrealistic assumptions back to what experience says
 */
export const caseModel = function(c, glossaryModel, findVariable, reverted) {
    const m = structuredClone(glossaryModel);
    for (const [name, value] of Object.entries(policyChangesOf(c))) findVariable(m.variables, name).equation = value;
    for (const a of c.assumptions) {
        const v = findVariable(m.variables, a.variable);
        v.documentation = a.note;
        if (a.value !== undefined) v.equation = reverted ? a.revert : a.value;
        for (const [name, [value, back]] of Object.entries(a.alongside || {})) findVariable(m.variables, name).equation = reverted ? back : value;
    }
    return m;
};
