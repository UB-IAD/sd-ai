/**
 * Shared vocabulary for the evaluation pages: what a group's name says about its tests, what a
 * category's role is, and which leaderboard a category belongs to.
 *
 * The agent categories split each of their groups by rule (evals/utilities/heldOut.js): held-out
 * tests move to `<group>HeldOut`, and the harder variants live in `<group>Hard` and
 * `<group>Hard2`. The pages read those suffixes so a reader never has to decode a group name.
 */

import { leaderboardConfig, LEADERBOARD_ORDER } from './leaderboardMeta';

/** What kind of tests a group holds, from its name. */
export function groupKind(groupName) {
  const heldOut = /HeldOut$/.test(groupName);
  const hard2 = /Hard2/.test(groupName);
  const hard = /Hard/.test(groupName);
  return { heldOut, hard, hard2 };
}

/** A short label for a group's kind, or null for an ordinary group of an engine category. */
export function groupKindLabel(groupName, isAgentCategory) {
  if (!isAgentCategory) return null;
  const { heldOut, hard, hard2 } = groupKind(groupName);
  const parts = [];
  if (hard2) parts.push('hard (second rule)');
  else if (hard) parts.push('hard');
  else parts.push('ordinary');
  parts.push(heldOut ? 'held out' : 'dev');
  return parts.join(', ');
}

/** The sentence that explains a group's kind, for a test page. */
export function groupKindExplanation(groupName) {
  const { heldOut, hard, hard2 } = groupKind(groupName);
  const split = heldOut
    ? 'Held out: built from a scenario, model, diagram or document set written after this category’s grader was frozen, and never used to tune it. A score here is the honest one.'
    : 'Dev: built from material the grader was developed and checked against. A score here can be flattering, because the grader was tuned while looking at cases like it.';
  let difficulty = 'Ordinary difficulty: the task as a careful modeler would normally be asked it.';
  if (hard2) {
    difficulty =
      'Hard, second rule: a further difficulty lever added in Phase 3 for categories whose first hard group was still too easy, generated by rule on held-out material only and never selected by which cases an agent failed.';
  } else if (hard) {
    difficulty =
      'Hard: the same task with a difficulty lever applied by rule (for example no hint about the method, several faults of different kinds plus a clean model, feedback withheld, or numbers graded instead of shapes). Hard groups exist so that a strong agent and a weak one score differently.';
  }
  return `${difficulty} ${split}`;
}

