/**
 * The leaderboards a category is scored on, from the board copy in leaderboardMeta (every column
 * of every board is described there, so it is the one list that names them all). A category can
 * appear on more than one board; conformance is scored on both diagram boards.
 */
export function boardsForCategory(categoryName) {
  return LEADERBOARD_ORDER.filter((mode) => leaderboardConfig[mode]?.categoryNotes?.[categoryName]);
}
